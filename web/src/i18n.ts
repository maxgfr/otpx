export const dictionaries = { en: en as Record<Key, string>, de };
export type Lang = keyof typeof dictionaries;

let lang: Lang = 'en';

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
}

export function getLang(): Lang {
  return lang;
}

/** English unless German was picked in the settings: the browser language is not used. */
export function detectLang(preferred?: string | null): Lang {
  return preferred === 'de' ? 'de' : 'en';
}

/** Translated text with `{name}` placeholders filled. */
export function t(key: Key, vars: Record<string, string | number> = {}): string {
  const text = dictionaries[lang][key] ?? en[key];
  return text.replace(/\{(\w+)\}/g, (m, k: string) => (k in vars ? String(vars[k]) : m));
}

/** Plural form `base.one` / `base.other` for `n` (French counts 0 as singular). */
export function tn(
  base: 'add.done' | 'add.scan.found' | 'receive.lead' | 'unlock.wrong.pin',
  n: number,
  vars: Record<string, string | number> = {},
): string {
  const rule = new Intl.PluralRules(lang).select(n) === 'one' ? 'one' : 'other';
  return t(`${base}.${rule}` as Key, { ...vars, n });
}

/** "3 min", "2 h"… */
export function duration(secs: number): string {
  if (secs < 60) return t('time.s', { n: Math.round(secs) });
  if (secs < 3600) return t('time.m', { n: Math.round(secs / 60) });
  if (secs < 86400) return t('time.h', { n: Math.round(secs / 3600) });
  return t('time.d', { n: Math.round(secs / 86400) });
}
